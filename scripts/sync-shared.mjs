#!/usr/bin/env node
/**
 * Copies the pure game engine (src/domain) and the seed data into
 * supabase/functions/_shared so the Edge Functions (Deno) run exactly the same
 * rules as the app. Deno needs explicit file extensions, so relative imports are
 * rewritten from './x' to './x.ts'.
 *
 *   node scripts/sync-shared.mjs          write the copy
 *   node scripts/sync-shared.mjs --check  exit 1 if the copy is out of date (CI)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const seedSrc = join(root, 'seed');
const sharedDir = join(root, 'supabase', 'functions', '_shared');
/** Pure TypeScript folders copied as-is (no react, expo or npm imports allowed in them). */
const PURE_DIRS = ['domain', 'backend'];
const seedOut = join(sharedDir, 'seed');

const header = (source) => `// GENERATED by scripts/sync-shared.mjs from ${source}. Do not edit here.\n`;
const SEED_FILES = ['challenges.json', 'creatures.json', 'milestones.json', 'reward_suggestions.json'];

function listTs(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return listTs(full);
    return name.endsWith('.ts') ? [full] : [];
  });
}

/** './x' -> './x.ts' for relative specifiers without an extension. */
export function addExtensions(source, fileDir) {
  return source.replace(/(from\s+['"])(\.{1,2}\/[^'"]+)(['"])/g, (match, pre, spec, post) => {
    if (/\.(ts|json)$/.test(spec)) return match;
    const asDir = join(fileDir, spec);
    const target = existsSync(asDir) && statSync(asDir).isDirectory() ? `${spec}/index.ts` : `${spec}.ts`;
    return `${pre}${target}${post}`;
  });
}

const CATALOG = `${header('src/data/catalog.ts')}
import challenges from './seed/challenges.json' with { type: 'json' };
import creatures from './seed/creatures.json' with { type: 'json' };
import milestones from './seed/milestones.json' with { type: 'json' };
import rewardSuggestions from './seed/reward_suggestions.json' with { type: 'json' };

import type {
  Catalog,
  ChallengeTemplate,
  CreatureSpecies,
  Milestone,
  RewardSuggestion,
  SpecialCreature,
  WorldInfo,
} from './domain/types.ts';

export const catalog: Catalog = {
  templates: challenges as unknown as ChallengeTemplate[],
  worlds: creatures.worlds as unknown as WorldInfo[],
  species: creatures.species as unknown as CreatureSpecies[],
  specials: creatures.specials as unknown as SpecialCreature[],
  milestones: milestones as unknown as Milestone[],
  rewardSuggestions: rewardSuggestions as unknown as RewardSuggestion[],
};
`;

/** Every generated file as { path relative to _shared, content }. */
export function buildSharedFiles() {
  const files = PURE_DIRS.flatMap((dir) => {
    const src = join(root, 'src', dir);
    return listTs(src).map((file) => {
      const rel = relative(src, file);
      const content = header(`src/${dir}`) + addExtensions(readFileSync(file, 'utf8'), dirname(file));
      return { path: join(dir, rel), content };
    });
  });
  for (const name of SEED_FILES) {
    files.push({ path: join('seed', name), content: readFileSync(join(seedSrc, name), 'utf8') });
  }
  files.push({ path: 'catalog.ts', content: CATALOG });
  return files;
}

function main() {
  const check = process.argv.includes('--check');
  const files = buildSharedFiles();
  if (check) {
    const stale = files.filter(({ path, content }) => {
      const target = join(sharedDir, path);
      return !existsSync(target) || readFileSync(target, 'utf8') !== content;
    });
    if (stale.length) {
      console.error(`Out of date: ${stale.map((f) => f.path.split(sep).join('/')).join(', ')}`);
      console.error('Run: npm run sync:shared');
      process.exit(1);
    }
    console.log('supabase/functions/_shared is up to date.');
    return;
  }
  for (const dir of PURE_DIRS) rmSync(join(sharedDir, dir), { recursive: true, force: true });
  rmSync(seedOut, { recursive: true, force: true });
  for (const { path, content } of files) {
    const target = join(sharedDir, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`Wrote ${files.length} files to supabase/functions/_shared.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
