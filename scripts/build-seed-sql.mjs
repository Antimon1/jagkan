#!/usr/bin/env node
/**
 * Generates the catalog migration (challenge_templates, creatures, milestones)
 * from seed/*.json. The statements are upserts, so a later migration generated
 * the same way updates the catalog in place.
 *
 *   node scripts/build-seed-sql.mjs           rewrite the latest catalog migration (only before it is applied)
 *   node scripts/build-seed-sql.mjs --new     add a new catalog migration (after editing seed/*.json)
 *   node scripts/build-seed-sql.mjs --check   exit 1 if the latest catalog migration is stale (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = join(root, 'supabase', 'migrations');
const FIRST_CATALOG = '20261011000300_catalog.sql';

/** The newest *_catalog.sql migration; it must always match seed/*.json. */
function latestCatalogMigration() {
  const files = readdirSync(MIGRATIONS).filter((f) => f.endsWith('_catalog.sql')).sort();
  return join(MIGRATIONS, files.at(-1) ?? FIRST_CATALOG);
}

function newMigrationPath() {
  const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14);
  return join(MIGRATIONS, `${stamp}_catalog.sql`);
}

const readSeed = (name) => JSON.parse(readFileSync(join(root, 'seed', name), 'utf8'));

export function sqlText(value) {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

const sqlBool = (value) => (value ? 'true' : 'false');
const sqlInt = (value) => (value === null || value === undefined ? 'null' : String(Number.parseInt(value, 10)));
const sqlTextArray = (values) => `array[${values.map(sqlText).join(', ')}]::text[]`;
const sqlJson = (value) => (value === null || value === undefined ? 'null' : `${sqlText(JSON.stringify(value))}::jsonb`);

function upsert(table, columns, rows) {
  const updates = columns.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ');
  const values = rows.map((row) => `  (${row.join(', ')})`).join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${values}\non conflict (id) do update set ${updates};\n`;
}

export function buildCatalogSql() {
  const challenges = readSeed('challenges.json');
  const creatures = readSeed('creatures.json');
  const milestones = readSeed('milestones.json');

  const templateRows = challenges.map((t) => [
    sqlText(t.id), sqlText(t.branch), sqlInt(t.ageMin), sqlInt(t.ageMax), sqlInt(t.difficulty), sqlText(t.titleChild),
    sqlText(t.titleParent), sqlText(t.icon), sqlText(t.parentTip), sqlBool(t.repeatable), sqlTextArray(t.tags ?? []),
    sqlBool(t.isPlus), sqlText(t.reward),
  ]);
  const creatureRows = [
    ...creatures.species.flatMap((s) =>
      s.stages.map((stage) => [
        sqlText(`${s.id}_s${stage.stage}`), sqlText(s.world), sqlText(s.branch), sqlInt(s.slot), sqlInt(stage.stage),
        sqlText(stage.name), sqlText(stage.assetKey), 'false', 'null',
      ]),
    ),
    ...creatures.specials.map((s) => [
      sqlText(s.id), sqlText(s.world), 'null', 'null', 'null', sqlText(s.name), sqlText(s.assetKey), 'true', sqlJson(s.unlock),
    ]),
  ];
  const milestoneRows = milestones.map((m) => [
    sqlText(m.id), sqlInt(m.thresholdStars), sqlText(m.title), sqlText(m.backgroundKey), sqlText(m.emoji),
  ]);

  return [
    '-- GENERATED by scripts/build-seed-sql.mjs from seed/*.json. Do not edit by hand.',
    `-- ${templateRows.length} challenges, ${creatureRows.length} creature rows, ${milestoneRows.length} milestones.`,
    '',
    upsert(
      'challenge_templates',
      ['id', 'branch', 'age_min', 'age_max', 'difficulty', 'title_child', 'title_parent', 'icon', 'parent_tip', 'repeatable', 'tags', 'is_plus', 'reward'],
      templateRows,
    ),
    upsert(
      'creatures',
      ['id', 'world', 'branch', 'family_slot', 'stage', 'name', 'asset_key', 'is_special', 'unlock_rule'],
      creatureRows,
    ),
    upsert('milestones', ['id', 'threshold_stars', 'title', 'background_key', 'emoji'], milestoneRows),
  ].join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const sql = buildCatalogSql();
  if (args.includes('--check')) {
    const latest = latestCatalogMigration();
    if (!existsSync(latest) || readFileSync(latest, 'utf8') !== sql) {
      console.error('The catalog migration is out of date. Run: npm run seed:sql -- --new');
      process.exit(1);
    }
    console.log('Catalog migration is up to date.');
    return;
  }
  const out = args.includes('--new') ? newMigrationPath() : latestCatalogMigration();
  writeFileSync(out, sql);
  console.log(`Wrote ${out}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
